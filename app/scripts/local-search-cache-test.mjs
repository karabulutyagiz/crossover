import assert from 'node:assert/strict';
import { LocalSearchCache } from '../src/performance/localSearchCache.ts';
let now = 0;
const cache = new LocalSearchCache(2, 100, () => now);
cache.put('room-a:all', 'ga', ['Galatasaray']);
assert.deepEqual(cache.get('room-a:all', ' ga '), ['Galatasaray']);
assert.equal(cache.get('room-b:all', 'ga'), undefined);
assert.equal(cache.get('room-a:country', 'ga'), undefined);
cache.put('room-a:all', 'gal', []);
assert.deepEqual(cache.get('room-a:all', 'gal'), []);
cache.get('room-a:all', 'ga');
cache.put('room-a:all', 'bar', ['Barcelona']);
assert.equal(cache.get('room-a:all', 'gal'), undefined);
now = 100;
assert.equal(cache.get('room-a:all', 'ga'), undefined);
cache.put('room-a:all', 'ga', ['new']);
cache.clear();
assert.equal(cache.get('room-a:all', 'ga'), undefined);
console.log('PASS: local search isolation, empty hits, expiry, LRU and reconnect reset');
